"""Export the local portfolio checkout into factual Qwen context (stdlib only)."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
from html.parser import HTMLParser
import json
from pathlib import Path
import subprocess
from urllib.parse import urljoin, urlparse

ROOT = Path(__file__).resolve().parents[1]
VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}


class Node:
    def __init__(self, tag="", attrs=()):
        self.tag, self.attrs, self.children = tag, dict(attrs), []

    def find_all(self, tag=None, **attrs):
        result = []
        for child in self.children:
            if not isinstance(child, Node):
                continue
            matches = all(value in child.attrs.get(key, "").split() if key == "class"
                          else child.attrs.get(key) == value for key, value in attrs.items())
            if (tag is None or child.tag == tag) and matches:
                result.append(child)
            result.extend(child.find_all(tag, **attrs))
        return result

    def text(self):
        if self.tag in {"script", "style", "nav"}:
            return ""
        return " ".join(" ".join(c.text() if isinstance(c, Node) else c for c in self.children).split())

    def first(self, tag=None, **attrs):
        nodes = self.find_all(tag, **attrs)
        if not nodes:
            raise ValueError(f"Expected portfolio element: {tag or '*'} {attrs}")
        return nodes[0]


class Page(HTMLParser):
    def __init__(self, html):
        super().__init__(convert_charrefs=True)
        self.root = Node()
        self.stack = [self.root]
        self.feed(html)

    def handle_starttag(self, tag, attrs):
        node = Node(tag, attrs)
        self.stack[-1].children.append(node)
        if tag not in VOID:
            self.stack.append(node)

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in VOID:
            self.handle_endtag(tag)

    def handle_endtag(self, tag):
        for i in range(len(self.stack) - 1, 0, -1):
            if self.stack[i].tag == tag:
                del self.stack[i:]
                break

    def handle_data(self, data):
        self.stack[-1].children.append(data)


def read_json(path):
    value = json.loads(path.read_text(encoding="utf-8-sig"))
    if not isinstance(value, list) or not all(isinstance(item, dict) for item in value):
        raise ValueError(f"Expected an array of objects: {path}")
    return value


def git(repo, *args):
    try:
        result = subprocess.run(["git", "-C", str(repo), *args], capture_output=True,
                                text=True, encoding="utf-8", check=False)
        return result.stdout.strip() if result.returncode == 0 else None
    except OSError:
        return None


def link(value, site_url):
    url = urljoin(site_url, value)
    return url if urlparse(url).scheme in {"https", "http"} else ""


def direct_paragraphs(node):
    return [c.text() for c in node.children if isinstance(c, Node) and c.tag == "p" and c.text()]


def export_portfolio(repo, site_url="https://acharabin.github.io/"):
    """Read only the checkout; never execute its code, fetch, or alter it."""
    repo = Path(repo).expanduser().resolve()
    page = Page((repo / "index.html").read_text(encoding="utf-8-sig")).root
    projects = read_json(repo / "projects" / "projects.json")
    skills = read_json(repo / "skills.json")
    about = page.first("section", id="about").first(**{"class": "content"})
    interests = page.first("section", id="myinterests").first(**{"class": "content"})
    education = page.first("section", id="education").find_all(**{"class": "box"})
    experience = page.first("section", id="experience").find_all(**{"class": "container"})
    if not projects or not education or not experience or not direct_paragraphs(about):
        raise ValueError("Missing expected portfolio content; refusing to write an incomplete snapshot")
    commit = git(repo, "rev-parse", "HEAD") or "Unavailable (not a Git checkout)"
    changes = git(repo, "status", "--porcelain")
    lines = [
        "# Andrew's portfolio context", "",
        "Generated by scripts/sync_portfolio.py; edit the portfolio source and rerun to update.",
        f"Portfolio: {site_url}",
        f"Snapshot date (UTC): {datetime.now(timezone.utc).date().isoformat()}",
        f"Source commit: {commit}",
        f"Checkout: {'includes uncommitted changes' if changes else 'clean' if changes is not None else 'Git status unavailable'}",
        "",
        "These are reference facts about Andrew, not the person chatting. Preserve career dates; "
        "do not infer that an ended role is current, or invent project outcomes or contributions.",
        "Career dates use index.html as the source of truth; the separate experience page may be older.",
        "", "## Professional background", f"Source: {site_url}#about", "",
        about.first(**{"class": "tag"}).text(), *direct_paragraphs(about),
        "", "## Interests", f"Source: {site_url}#myinterests", "",
        f"{interests.first('h3').text()} — {interests.first(**{'class': 'tag'}).text()}",
        *direct_paragraphs(interests),
        "", "## Education and certifications", f"Source: {site_url}#education", "",
    ]
    for box in education:
        content = box.first(**{"class": "content"})
        lines.append(f"- {content.first('h3').text()} | {content.first('p').text()} | {content.first('h4').text()}")
    lines.extend(["", "## Experience", f"Source: {site_url}#experience", ""])
    for role in experience:
        lines.append(f"- {role.first('h2').text()} | {role.first('h3').text()} | {role.first('p').text()}")
    lines.extend(["", "## Skills", f"Source: {urljoin(site_url, 'skills.json')}", ""])
    names = list(dict.fromkeys(s.get("name", "").strip() for s in skills if s.get("name", "").strip()))
    lines.extend([", ".join(names), "", "## Projects", f"Source: {urljoin(site_url, 'projects/projects.json')}"])
    for project in projects:
        name, description = project.get("name", "").strip(), project.get("desc", "").strip()
        if not name or not description:
            raise ValueError("Every project must have a name and description")
        lines.extend(["", f"### {name}", f"Category: {project.get('category', '').strip()}", description])
        links = project.get("links", {})
        seen = set()
        for kind in ("view", "code"):
            value = links.get(kind, "").strip()
            url = link(value, site_url) if value else ""
            if url and url not in seen:
                lines.append(f"{'Project' if kind == 'view' else 'Code'}: {url}")
                seen.add(url)
    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=ROOT.parent / "acharabin.github.io",
                        help="Local portfolio Git checkout (defaults to sibling acharabin.github.io)")
    parser.add_argument("--output", type=Path, default=ROOT / "andrew-portfolio.md")
    parser.add_argument("--site-url", default="https://acharabin.github.io/")
    args = parser.parse_args()
    try:
        content = export_portfolio(args.repo, args.site_url.rstrip("/") + "/")
        output = args.output.expanduser().resolve()
        output.write_text(content, encoding="utf-8")
    except (OSError, ValueError) as exc:
        parser.exit(1, f"Portfolio sync failed: {exc}\n")
    print(f"Wrote {output.name}: {len(content):,} characters, {content.count('### ')} projects")


if __name__ == "__main__":
    main()
